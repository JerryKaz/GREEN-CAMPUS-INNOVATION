#!/usr/bin/env node
// Writes assets/js/config.js from environment variables (deploy-time).
// Refuses to run if a service_role key is supplied as the anon key.
import { writeFileSync, existsSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
if (existsSync(join(root, '.env'))) {
  for (const line of readFileSync(join(root, '.env'), 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^['"]|['"]$/g, '');
  }
}
const env = process.env;
const key = env.SUPABASE_ANON_KEY ?? '';

// A JWT's payload states its role — block service_role keys outright.
try {
  const payload = JSON.parse(Buffer.from(key.split('.')[1] ?? '', 'base64url').toString() || '{}');
  if (payload.role === 'service_role') {
    console.error('Refusing to build: SUPABASE_ANON_KEY is a service_role key.');
    process.exit(1);
  }
} catch { /* non-JWT publishable keys are fine */ }
if (key.startsWith('sb_secret_')) {
  console.error('Refusing to build: secret keys must never ship to the browser.');
  process.exit(1);
}

const config = {
  SUPABASE_URL: env.SUPABASE_URL ?? '',
  SUPABASE_ANON_KEY: key,
  SHOW_DEMO_DATA: (env.SHOW_DEMO_DATA ?? 'false') === 'true',
  MAP_CENTER: [Number(env.MAP_CENTER_LAT ?? 5.6037), Number(env.MAP_CENTER_LNG ?? -0.187)],
  MAP_ZOOM: Number(env.MAP_ZOOM ?? 16),
  SITE_URL: env.SITE_URL ?? 'https://greencampusinnovation.com',
};
writeFileSync(join(root, 'assets/js/config.js'),
  `// Generated by scripts/build-config.mjs — do not commit secrets.\nexport const CONFIG = ${JSON.stringify(config, null, 2)};\n`);
console.log(`config.js written (${config.SUPABASE_URL ? 'Supabase mode' : 'demo mode'})`);
